"""One-off: upload the course/book download files to Supabase Storage and write the migration that publishes them.

    python -m app.tools.upload_material --material ../material

Reads SUPABASE_URL and SUPABASE_SERVICE_ROLE_KEY from the environment or the backend's .env file.
Files go to a PUBLIC bucket (`products`) under unguessable names, the same access model the books
had on Cloudinary: anyone holding the emailed link can download, nobody can list the bucket.

What it does
  * Courses: uploads each course zip from the material folder as it is (3 PDFs per zip).
  * Books: builds one zip per book (the main PDF plus its free companion booklet) and uploads it.
  * Writes supabase/migrations/0009_product_files.sql: `update catalog_items set pdf_url=..., active=true`
    for every file that uploaded. Items whose upload failed stay inactive (see 0008), so nothing
    sellable ever has an empty download link. Review the SQL, then run it in Supabase.

Credentials are never printed or written anywhere. Zips are treated as untrusted: they are read
with `zipfile` into memory, never executed. The Supabase free plan caps a single file at 50 MB;
failures are reported per file and the exit code is 1 when any upload failed.
"""

from __future__ import annotations

import argparse
import io
import secrets
import sys
import zipfile
from dataclasses import dataclass
from pathlib import Path

import httpx

from app.core.config import settings

MIGRATION_PATH = Path(__file__).resolve().parents[2] / "supabase" / "migrations" / "0009_product_files.sql"
BUCKET = "products"
MAX_FILE_BYTES = 50 * 1024 * 1024  # Supabase free-plan per-file limit


@dataclass(frozen=True)
class Product:
    item_id: str
    file_name: str  # readable part of the stored name; a random prefix is added at upload
    source_zip: str  # file name inside the material folder
    # None: upload source_zip as-is. Otherwise build a new zip from these member suffixes of source_zip.
    members: tuple[str, ...] | None = None


PRODUCTS: tuple[Product, ...] = (
    Product("course-ttc200", "RYS-TTC200-Study-Set.zip", "Maharishi-Yoga-Peeth_TTC-200_PDFs.zip"),
    Product("course-retreat10", "10-Day-Retreat-Study-Set.zip", "Maharishi-Yoga-Peeth_Retreat_PDFs.zip"),
    Product("course-ttc300", "RYS-TTC300-Study-Set.zip", "Maharishi-Yoga-Peeth_TTC-300_PDFs.zip"),
    Product("course-ttc500", "RYS-TTC500-Study-Set.zip", "Maharishi-Yoga-Peeth_TTC-500_PDFs.zip"),
    Product("course-tantra", "Tantra-Study-Set.zip", "Maharishi-Yoga-Peeth_Tantra_PDFs_A5.zip"),
    Product("book-ayurveda", "Old-Farts-Guide-to-Ayurveda.zip", "Old-Farts-Guide-Launch-Kit ayeurveda.zip",
            ("1 Books/The-Old-Farts-Guide-to-Ayurveda.pdf", "1 Books/Ayurveda-Plants-Guide-Booklet.pdf")),
    Product("book-forex", "Old-Farts-Guide-to-Savings-and-Forex.zip", "Old-Farts-Guide-Savings-Forex_Launch-Kit.zip",
            ("01 The Old Fart's Guide to Savings & Forex Trading.pdf", "02 The Old Fart's Guide to Trade Ruler - Companion Booklet.pdf")),
    Product("book-vedic-gods", "Old-Farts-Guide-to-Vedic-Gods.zip", "Vedic-Gods-Set-Old-Farts-Collection.zip",
            ("1 Books (PDF)/Old-Farts-Guide-to-Vedic-Gods-A5.pdf", "1 Books (PDF)/Old-Farts-Guide-to-Mantras-A5.pdf")),
)


def build_book_zip(source_zip: Path, members: tuple[str, ...]) -> bytes:
    """A new zip holding just `members` (matched by path suffix), flattened to bare file names."""
    out = io.BytesIO()
    with zipfile.ZipFile(source_zip) as src, zipfile.ZipFile(out, "w", zipfile.ZIP_DEFLATED) as dst:
        names = src.namelist()
        for wanted in members:
            match = next((n for n in names if n.replace("\\", "/").endswith(wanted)), None)
            if match is None:
                raise FileNotFoundError(f"{wanted!r} not found in {source_zip.name}")
            dst.writestr(Path(wanted).name, src.read(match))  # basename only: no path can escape the archive
    return out.getvalue()


def sql_literal(value: str) -> str:
    return "'" + value.replace("'", "''") + "'"


def build_migration(uploaded: dict[str, str], failed: list[str]) -> str:
    lines = [
        "-- Generated by `python -m app.tools.upload_material`. Review, then run in Supabase.",
        "-- Publishes each item whose file uploaded. Items listed as failed stay inactive (see 0008).",
        "",
    ]
    for item_id, url in sorted(uploaded.items()):
        lines.append(f"update public.catalog_items set pdf_url = {sql_literal(url)}, active = true where id = {sql_literal(item_id)};")
    for item_id in sorted(failed):
        lines.append(f"-- NOT UPLOADED: {item_id} stays inactive")
    return "\n".join(lines) + "\n"


def ensure_bucket(client: httpx.Client, base: str, headers: dict[str, str]) -> None:
    """Create the public bucket if it is missing (an 'already exists' reply is fine)."""
    resp = client.post(f"{base}/storage/v1/bucket", headers=headers,
                       json={"id": BUCKET, "name": BUCKET, "public": True, "file_size_limit": MAX_FILE_BYTES})
    if resp.status_code not in (200, 201, 400, 409):
        raise RuntimeError(f"could not create bucket: HTTP {resp.status_code}")


def upload_file(client: httpx.Client, base: str, headers: dict[str, str], file_name: str, data: bytes) -> str:
    """Upload one file under a random prefix and return its public URL."""
    if len(data) > MAX_FILE_BYTES:
        raise RuntimeError(f"{len(data) / 1_048_576:.1f} MB is over the 50 MB per-file limit")
    path = f"{secrets.token_urlsafe(12)}/{file_name}"
    resp = client.post(f"{base}/storage/v1/object/{BUCKET}/{path}", headers={**headers, "Content-Type": "application/zip"},
                       content=data, timeout=600)
    if resp.status_code not in (200, 201):
        detail = resp.json().get("message") if resp.content else None
        raise RuntimeError(detail or f"HTTP {resp.status_code}")
    return f"{base}/storage/v1/object/public/{BUCKET}/{path}"


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--material", required=True, type=Path, help="folder holding the course/book zips")
    ap.add_argument("--dry-run", action="store_true", help="build every file and report sizes, upload nothing")
    args = ap.parse_args(argv)

    base, key = settings.supabase_url.rstrip("/"), settings.supabase_service_role_key
    if not args.dry_run and not (base and key):
        print("SUPABASE_URL and SUPABASE_SERVICE_ROLE_KEY are empty: set them in the environment or the backend's .env (or use --dry-run).", file=sys.stderr)
        return 2
    headers = {"Authorization": f"Bearer {key}", "apikey": key}

    uploaded: dict[str, str] = {}
    failed: list[str] = []
    total = 0
    with httpx.Client() as client:
        if not args.dry_run:
            ensure_bucket(client, base, headers)
        for p in PRODUCTS:
            try:
                source = args.material / p.source_zip
                data = build_book_zip(source, p.members) if p.members else source.read_bytes()
                total += len(data)
                print(f"{p.item_id}: {len(data) / 1_048_576:.1f} MB", end=" ... ", flush=True)
                if args.dry_run:
                    print("dry run")
                    continue
                uploaded[p.item_id] = upload_file(client, base, headers, p.file_name, data)
                print("uploaded")
            except Exception as exc:  # report and carry on: one oversize file must not block the rest
                failed.append(p.item_id)
                print(f"FAILED ({exc})")

    print(f"\nTotal: {total / 1_048_576:.1f} MB")
    if args.dry_run:
        return 0
    MIGRATION_PATH.write_text(build_migration(uploaded, failed), encoding="utf-8")
    print(f"Wrote {MIGRATION_PATH} ({len(uploaded)} published, {len(failed)} failed).")
    return 1 if failed else 0


if __name__ == "__main__":
    sys.exit(main())
